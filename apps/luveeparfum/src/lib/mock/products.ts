export function getMockProducts(
  options: {
    limit?: number;
    categorySlug?: string;
    brandName?: string;
    featured?: boolean;
  } = {},
): ProductCardProps[] {
  let list = [...MOCK_PRODUCTS];

  if (options.categorySlug) {
    const categoryMap: Record<string, string[]> = {
      'tenis-calcados': ['NexRun', 'StyleBase'],
      'roupas-moda': ['UrbanCo', 'StyleBase', 'ActivePro'],
      acessorios: ['UrbanCo', 'StyleBase', 'PrecisionTime'],
      eletronicos: ['TechGear'],
      'esportes-fitness': ['ActivePro', 'NexRun'],
      'mochilas-bags': ['UrbanCo'],
    };
    const brands = categoryMap[options.categorySlug];
    if (brands) list = list.filter((p) => p.brand && brands.includes(p.brand));
  }

  if (options.brandName) {
    list = list.filter((p) => p.brand?.toLowerCase() === options.brandName?.toLowerCase());
  }

  if (options.featured) {
    list = list.filter((p) => p.badge !== null).slice(0, 8);
  }

  return list.slice(0, options.limit ?? 20).map((p) => ({
    id: p.id,
    title: p.title,
    handle: p.handle,
    price: p.price,
    originalPrice: p.originalPrice,
    discountPercent: p.discountPercent,
    imageUrl: p.imageUrl,
    brand: p.brand,
    badge: p.badge,
    variantId: p.variantId,
  }));
}
